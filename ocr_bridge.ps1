param(
    [ValidateSet('Status', 'Recognize', 'Install', 'ElevatedInstall')][string]$Mode = 'Status',
    [string]$ImagePath,
    [ValidateSet('ko-KR', 'en-US')][string]$Language = 'ko-KR',
    [string]$ResultPath
)
$ErrorActionPreference = 'Stop'
$stage = 'setup'
[Console]::OutputEncoding = [System.Text.UTF8Encoding]::new($false)

function Write-Result($Data) {
    $json = ConvertTo-Json -InputObject $Data -Depth 6 -Compress
    if ($Mode -eq 'ElevatedInstall') {
        [System.IO.File]::WriteAllText($ResultPath, $json, [System.Text.UTF8Encoding]::new($false))
    } else { [Console]::WriteLine($json) }
}

try {
    if ($Mode -eq 'Install') {
        # The path is generated by this app, never supplied as executable code.
        $arguments = '-NoProfile -NonInteractive -ExecutionPolicy Bypass -File "{0}" -Mode ElevatedInstall -ResultPath "{1}"' -f $PSCommandPath, $ResultPath
        $process = Start-Process -FilePath "$PSHOME\powershell.exe" -ArgumentList $arguments -Verb RunAs -WindowStyle Hidden -Wait -PassThru
        if (Test-Path -LiteralPath $ResultPath) {
            [Console]::WriteLine([System.IO.File]::ReadAllText($ResultPath))
        } else { throw "OCR language installation did not return a result (exit $($process.ExitCode))." }
        exit
    }
    if ($Mode -eq 'ElevatedInstall') {
        $restart = $false
        foreach ($tag in @('ko-KR', 'en-US')) {
            foreach ($feature in @('Basic', 'OCR')) {
                $name = 'Language.{0}~~~{1}~0.0.1.0' -f $feature, $tag
                $capability = Get-WindowsCapability -Online -Name $name
                if ($capability.State -ne 'Installed') {
                    $added = Add-WindowsCapability -Online -Name $name
                    $restart = $restart -or $added.RestartNeeded
                }
            }
        }
        Write-Result @{ok=$true; restart=$restart}
        exit
    }
    Add-Type -AssemblyName System.Runtime.WindowsRuntime
    $null = [Windows.Media.Ocr.OcrEngine, Windows.Foundation, ContentType=WindowsRuntime]
    $null = [Windows.Globalization.Language, Windows.Foundation, ContentType=WindowsRuntime]
    if ($Mode -eq 'Status') {
        $languages = @([Windows.Media.Ocr.OcrEngine]::AvailableRecognizerLanguages | ForEach-Object { $_.LanguageTag })
        Write-Result @{ok=$true; languages=$languages; max_dimension=[Windows.Media.Ocr.OcrEngine]::MaxImageDimension}
        exit
    }
    function Await-Operation($Operation, [Type]$ResultType) {
        $method = [System.WindowsRuntimeSystemExtensions].GetMethods() | Where-Object {
            $_.Name -eq 'AsTask' -and $_.IsGenericMethod -and $_.GetGenericArguments().Count -eq 1 -and
            $_.GetParameters().Count -eq 1 -and $_.GetParameters()[0].ParameterType.Name -eq 'IAsyncOperation`1'
        } | Select-Object -First 1
        $task = $method.MakeGenericMethod($ResultType).Invoke($null, @($Operation))
        $task.GetAwaiter().GetResult()
    }
    $null = [Windows.Storage.StorageFile, Windows.Storage, ContentType=WindowsRuntime]
    $null = [Windows.Storage.Streams.IRandomAccessStream, Windows.Storage.Streams, ContentType=WindowsRuntime]
    $null = [Windows.Graphics.Imaging.BitmapDecoder, Windows.Graphics.Imaging, ContentType=WindowsRuntime]
    $null = [Windows.Graphics.Imaging.SoftwareBitmap, Windows.Graphics.Imaging, ContentType=WindowsRuntime]
    $engine = [Windows.Media.Ocr.OcrEngine]::TryCreateFromLanguage([Windows.Globalization.Language]::new($Language))
    if ($null -eq $engine) { throw "OCR language is unavailable: $Language" }
    $file = Await-Operation ([Windows.Storage.StorageFile]::GetFileFromPathAsync($ImagePath)) ([Windows.Storage.StorageFile])
    $stream = Await-Operation ($file.OpenAsync([Windows.Storage.FileAccessMode]::Read)) ([Windows.Storage.Streams.IRandomAccessStream])
    try {
        $decoder = Await-Operation ([Windows.Graphics.Imaging.BitmapDecoder]::CreateAsync($stream)) ([Windows.Graphics.Imaging.BitmapDecoder])
        $bitmap = Await-Operation ($decoder.GetSoftwareBitmapAsync()) ([Windows.Graphics.Imaging.SoftwareBitmap])
        try {
            $stage = 'recognize'
            $result = Await-Operation ($engine.RecognizeAsync($bitmap)) ([Windows.Media.Ocr.OcrResult])
            $lines = @($result.Lines | ForEach-Object { $_.Text })
            Write-Result @{ok=$true; text=($lines -join "`n"); language=$Language}
        } finally { if ($bitmap) { $bitmap.Dispose() } }
    } finally { if ($stream) { $stream.Dispose() } }
} catch {
    Write-Result @{ok=$false; error=$_.Exception.Message; stage=$stage}
    exit 1
}
